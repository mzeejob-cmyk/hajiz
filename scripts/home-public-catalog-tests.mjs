import assert from "node:assert/strict"
import { readFile } from "node:fs/promises"

let passed=0
const test=async(name,fn)=>{await fn();passed++;console.log(`PASS ${name}`)}
const read=path=>readFile(new URL(path,import.meta.url),"utf8")
const component=await read("../src/features/home/components/HomePublicCatalogSection.jsx")
const packages=await read("../src/features/home/components/PackagesSection.jsx")
const offers=await read("../src/features/home/components/OffersSection.jsx")
const homeData=await read("../src/features/home/data/homeData.js")
const dataSource=await read("../src/services/publicCatalogDataSource.js")
const packagesPage=await read("../src/features/packages/PackagesPage.jsx")
const offersPage=await read("../src/features/offers/OffersPage.jsx")
const all=component+packages+offers

await test("Home Packages calls authoritative loadPackages",()=>assert.match(component,/dataSource\.loadPackages/))
await test("Home Offers calls authoritative loadOffers",()=>assert.match(component,/dataSource\.loadOffers/))
await test("public catalog data source reused",()=>assert.match(component,/publicCatalogDataSource/))
await test("packages inject shared component",()=>assert.match(packages,/HomePublicCatalogSection type="package"/))
await test("offers inject shared component",()=>assert.match(offers,/HomePublicCatalogSection type="offer"/))
await test("first three rows only",()=>assert.match(component,/rows\.slice\(0, 3\)/))
await test("response order preserved",()=>assert.equal(/sort\s*\(|reverse\s*\(|rank/i.test(component),false))
await test("package title rendered",()=>assert.match(component,/row\.title/))
await test("package summary rendered",()=>assert.match(component,/row\.summary/))
await test("offer title rendered",()=>assert.match(component,/row\.title/))
await test("offer summary rendered",()=>assert.match(component,/row\.summary/))
await test("package destination",()=>assert.match(packages,/destination="\/packages"/))
await test("offer destination",()=>assert.match(offers,/destination="\/offers"/))
await test("cards use safe destination",()=>assert.match(component,/to=\{destination\}/))
await test("no package price",()=>assert.equal(/price|displayPrice|AED|SDG|USD/i.test(all),false))
await test("no package duration",()=>assert.equal(/duration|ليال|أيام/.test(all),false))
await test("no discount",()=>assert.equal(/discount|خصم/.test(all),false))
await test("no supplier data",()=>assert.equal(/supplier|airline|hotel/i.test(all),false))
await test("no booking CTA",()=>assert.equal(/احجز|booking|checkout|reserve/i.test(all),false))
await test("no synthetic package fallback",()=>assert.equal(/CURATED_PACKAGES|أيام القاهرة|إسطنبول المختارة|عطلة دبي/.test(all+homeData),false))
await test("no synthetic offer fallback",()=>assert.equal(/SELECTED_OFFERS|عرض رحلة مختار|فنادق مختارة|ميزة تأمين السفر/.test(all+homeData),false))
await test("loading state",()=>assert.match(component,/status: "loading"/))
await test("package empty state",()=>assert.match(component,/لا توجد باقات منشورة متاحة حاليًا/))
await test("offer empty state",()=>assert.match(component,/لا توجد عروض منشورة متاحة حاليًا/))
await test("safe error state",()=>assert.match(component,/تعذر تحميل المحتوى المنشور حاليًا/))
await test("retry state",()=>assert.match(component,/إعادة المحاولة/))
await test("raw error not rendered",()=>assert.match(component,/\.catch\(\(\) =>/))
await test("packages page behavior retained",()=>assert.match(packagesPage,/PublicCatalogCollection type="package"/))
await test("offers page behavior retained",()=>assert.match(offersPage,/PublicCatalogCollection type="offer"/))
await test("search services retained",()=>assert.match(homeData,/SEARCH_SERVICES/))
await test("popular routes retained",()=>assert.match(homeData,/POPULAR_ROUTES/))
await test("hotel destinations retained",()=>assert.match(homeData,/HOTEL_DESTINATIONS/))
await test("Home adds no Authorization",()=>assert.equal(/Authorization/.test(all),false))
await test("Home adds no Supabase client",()=>assert.equal(/createClient|@supabase\/supabase-js|getAccountSessionClient/.test(all),false))
await test("Home has no direct DB",()=>assert.equal(/\.from\s*\(/.test(all),false))
await test("Home has no direct RPC",()=>assert.equal(/\.rpc\s*\(/.test(all),false))
await test("Home has no browser storage",()=>assert.equal(/localStorage|sessionStorage|indexedDB|document\.cookie/.test(all),false))
await test("Home has no catalog writes",()=>assert.equal(/create|update|delete|publish|unpublish/i.test(all),false))
await test("public source sends no Authorization",()=>assert.equal(/Authorization/.test(dataSource),false))
await test("public source stays read-only boundary",()=>assert.equal(/\.from\s*\(|\.rpc\s*\(|createClient/.test(dataSource),false))
assert.ok(passed>=32)
console.log(`\n${passed}/${passed} Home Public Catalog tests passed`)
